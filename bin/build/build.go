package main

import (
	"bufio"
	"bytes"
	"context"
	"flag"
	"fmt"
	"golang.org/x/sync/errgroup"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

var outputApp = flag.String("output-app", "ranger-ims-go", "Output app name")
var generateOnly = flag.Bool("generate-only", false, "Generate code, but don't build the app")

func main() {
	flag.Parse()
	start := time.Now()
	ctx := context.Background()
	ctx, cancel := context.WithTimeout(ctx, 10*time.Minute)
	defer cancel()

	repo, err := os.OpenRoot(repoRoot(ctx))
	must(err)

	eg, gCtx := errgroup.WithContext(ctx)
	eg.Go(func() error {
		mustRunInDir(exec.CommandContext(gCtx, "go", "tool", "sqlc", "generate"), repo.Name())
		return nil
	})
	eg.Go(func() error {
		mustRunInDir(exec.CommandContext(gCtx, "go", "tool", "templ", "generate"), repo.Name())
		return nil
	})
	eg.Go(func() error {
		output := mustRunInDir(exec.CommandContext(gCtx, "go", "tool", "tsc", "--listEmittedFiles"), repo.Name())
		for line := range strings.Lines(string(output)) {
			emitted, ok := strings.CutPrefix(strings.TrimSpace(line), "TSFILE: ")
			// Skip anything that isn't JS, e.g. source maps, which can't take a comment.
			if !ok || filepath.Ext(emitted) != ".js" {
				continue
			}
			// tsc reports absolute paths, but os.Root only accepts relative ones.
			rel, err := filepath.Rel(repo.Name(), emitted)
			must(err)
			addTSGeneratedHeader(repo, rel)
		}
		return nil
	})
	eg.Go(func() error {
		mustRunInDir(
			exec.CommandContext(gCtx, "go", "run", "fetchbuilddeps.go"),
			filepath.Join(repo.Name(), "bin", "fetchbuilddeps"),
		)
		return nil
	})
	must(eg.Wait())

	if *generateOnly {
		log.Printf("Code generation done in %v", time.Since(start))
		return
	}

	// #nosec G204
	mustRunInDir(exec.CommandContext(ctx, "go", "build", "-o", *outputApp), repo.Name())
	log.Printf("All done in %v. You can now run ./%v", time.Since(start), *outputApp)
}

func addTSGeneratedHeader(repo *os.Root, filename string) {
	// Read in the current version of the file.
	contents, err := repo.ReadFile(filename)
	must(err)

	// Re-open and truncate the file.
	f, err := repo.Create(filename)
	must(err)

	// WriteResponse the header, then the original file contents.
	_, err = f.WriteString("// Code generated by tsc. DO NOT EDIT.\n\n")
	must(err)
	scanner := bufio.NewScanner(bytes.NewReader(contents))
	for scanner.Scan() {
		_, err = f.WriteString(scanner.Text())
		must(err)
		_, err = f.WriteString("\n")
		must(err)
	}
	must(f.Close())
}

func mustRunInDir(cmd *exec.Cmd, dir string) []byte {
	start := time.Now()
	cmd.Dir = dir
	log.Printf("`%v`: running in %v", strings.Join(cmd.Args, " "), dir)
	output, err := cmd.CombinedOutput()
	if err != nil {
		log.Printf("`%v`: failed!", strings.Join(cmd.Args, " "))
		log.Printf("failed command output:\n%v", string(output))
		must(err)
	}
	log.Printf("`%v`: succeeded in %v", strings.Join(cmd.Args, " "), time.Since(start))
	return output
}

func repoRoot(ctx context.Context) string {
	// The GOMOD variable gives an absolute path to go.mod, which we use to find
	// the repo root directory
	cmd := exec.CommandContext(ctx, "go", "env", "GOMOD")
	goModPathBytes, err := cmd.CombinedOutput()
	must(err)
	repoRoot := filepath.Dir(strings.TrimSpace(string(goModPathBytes)))
	if !pathExists(os.Stat(repoRoot)) {
		must(fmt.Errorf("repo root %v does not exist", repoRoot))
	}
	return repoRoot
}

func pathExists(_ os.FileInfo, err error) bool {
	return !os.IsNotExist(err)
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
